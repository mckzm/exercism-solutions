// Package lasagna provides tools to cook lasagna.
package lasagna

const (
    // OvenTime represents the minutes the lasagna must cook in the oven.
    OvenTime        int = 40
    // TimePerLayer represents the preparation time in minutes for one layer.
    TimePerLayer int = 2
)

// RemainingOvenTime returns the remaining minutes based on the `actual` minutes already in the oven.
func RemainingOvenTime(actualMinutesInOven int) int {
	return OvenTime - actualMinutesInOven
}

// PreparationTime calculates the time needed to prepare the lasagna based on the amount of layers.
func PreparationTime(numberOfLayers int) int {
	return TimePerLayer * numberOfLayers
}

// ElapsedTime calculates the total time needed to create and bake a lasagna.
func ElapsedTime(numberOfLayers, actualMinutesInOven int) int {
	return PreparationTime(numberOfLayers) + actualMinutesInOven
}
